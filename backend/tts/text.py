"""Нормализация текста перед синтезом речи (Piper).

Голосовые предупреждения собираются программно и содержат аббревиатуры
(«СИЗ»), служебные символы из имён Re-ID («Гость_3», «#42») и лишние пробелы.
Без нормализации синтезатор читает их по буквам/неразборчиво. Здесь — чистая,
тестируемая функция приведения текста к «человеческой» русской речи.
"""
import re

# Аббревиатуры → произносимая форма (по целым словам, регистронезависимо).
_ABBREVIATIONS = {
    "сиз": "средств защиты",
}

_WORD_RE = re.compile(r"[А-Яа-яЁёA-Za-z]+")
_WS_RE = re.compile(r"\s+")


def normalize_for_tts(text: str) -> str:
    """Привести текст предупреждения к естественно произносимому русскому виду.

    Раскрывает аббревиатуры, убирает служебные символы из имён, схлопывает
    пробелы и добавляет завершающую пунктуацию для корректной интонации.
    """
    if not text:
        return ""
    # Служебные символы из имён/идентификаторов Re-ID.
    text = text.replace("_", " ").replace("#", " номер ")

    # Аббревиатуры — по словам (двоеточия/запятые рядом не мешают совпадению).
    def _repl(m: "re.Match") -> str:
        word = m.group(0)
        return _ABBREVIATIONS.get(word.lower(), word)

    text = _WORD_RE.sub(_repl, text)
    text = _WS_RE.sub(" ", text).strip()
    if text and text[-1] not in ".!?":
        text += "."
    return text
