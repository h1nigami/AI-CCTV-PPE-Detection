"""Формирование текста голосовой тревоги по списку нарушителей.

Чистая функция (без тяжёлых зависимостей вроде ultralytics) — вынесена из
`backend/main.py`, чтобы быть юнит-тестируемой без загрузки YOLO/InsightFace.
`main.py` реэкспортирует её как `_build_voice_text` для совместимости.
"""


def build_voice_text(voice_violators: list[tuple[str, list[str]]]) -> str:
    """Сформировать текст голосового предупреждения по списку нарушителей.

    `voice_violators` — список ``(имя, [отсутствующие СИЗ])`` ТОЛЬКО для людей,
    реально нарушающих В опасной зоне (внутри зоны, без пропуска, не хватает их
    собственных требуемых СИЗ). Ключевое: имя и список missing относятся к ОДНОМУ
    человеку, поэтому озвучка не припишет «нет каски» тому, кто в каске (раньше
    СИЗ агрегировались по всем людям в кадре, а имя бралось от первого — и человек
    в каске «слышал», что у него нет каски, если рядом стоял кто-то без каски).

    Пусто → ``""`` (ничего не озвучиваем — все в зоне экипированы либо нарушители
    только ВНЕ зоны). При нескольких нарушителях называем первого и добавляем
    «и ещё N». Имя берётся от конкретного нарушителя (по Re-ID, обычно «Гость_N»).
    """
    if not voice_violators:
        return ""
    name, _missing = voice_violators[0]
    who = name if name else "Гость"
    more = len(voice_violators) - 1
    tail = f" и ещё {more}" if more > 0 else ""
    return (f"{who}{tail}, обнаружено нарушение. "
            f"Информация передана отряду ликвидации")


def build_approved_voice_text(names: list[str]) -> str:
    """Спокойная голосовая отметка для людей с активным пропуском В зоне.

    `names` — имена людей с пропуском, стоящих в опасной зоне. Это НЕ тревога:
    проговаривается, что человек в зоне, но в средствах защиты, и причин для
    внимания нет. Пусто → ``""``. При нескольких — называем первого и «и ещё N».
    """
    names = [n for n in names] if names else []
    if not names:
        return ""
    who = names[0] if names[0] else "Работник"
    more = len(names) - 1
    tail = f" и ещё {more}" if more > 0 else ""
    return (f"{who}{tail} в опасной зоне, в средствах защиты. "
            f"Причин для внимания нет")
